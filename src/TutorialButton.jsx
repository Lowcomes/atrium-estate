export default function TutorialButton({ section, detail }) {
  const { s, r, go, toast } = useApp();
  const instance = useRef(null);
  const button = useRef(null);
  useEffect(() => () => instance.current?.destroy(), []);

  async function start() {
    let driver;
    try {
      ({ driver } = await import("driver.js"));
    } catch {
      toast(
        "Не удалось загрузить обучение. Обновите страницу и попробуйте снова.",
      );
      return;
    }
    if (!button.current || instance.current?.isActive()) return;
    const steps = screenSteps(section, detail, r, s, go);
    const hash = location.hash;
    const scroll = window.scrollY;
    const tour = driver({
      steps,
      animate: false,
      smoothScroll: false,
      disableActiveInteraction: true,
      showProgress: true,
      progressText: "Шаг {{current}} из {{total}}",
      prevBtnText: "Назад",
      nextBtnText: "Далее",
      doneBtnText: "Готово",
      closeBtnLabel: "Закрыть обучение",
      stageRadius: 9,
      stagePadding: 5,
      popoverOffset: 10,
      overlayColor: "#123a33",
      overlayOpacity: 0.48,
      popoverClass: "atrium-tutorial",
      onDestroyed: () => {
        instance.current = null;
        requestAnimationFrame(() => {
          if (location.hash === hash && button.current) {
            button.current.focus({ preventScroll: true });
            window.scrollTo({ top: scroll, behavior: "instant" });
          }
        });
      },
    });
    instance.current = tour;
    tour.drive();
  }

  return (
    <button
      type="button"
      ref={button}
      className="help-trigger"
      onClick={start}
      aria-haspopup="dialog"
    >
      <CircleHelp size={16} aria-hidden="true" />
      <span>Обучение</span>
    </button>
  );
}
